"""
policy_engine.py — DAG dependency unroller, conflict detector, and manifest compiler.
Evaluates queued policies, unrolls required prerequisites, and compiles deployment YAML.
"""

import json
import sqlite3
from pathlib import Path
from typing import Any

DB_PATH = Path(__file__).parent / "policies.db"

def get_db_connection() -> sqlite3.Connection:
    # Open SQLite in read-only URI mode to guarantee zero write locks at runtime
    conn = sqlite3.connect(f"file:{DB_PATH.resolve()}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    return conn

def search_policies(query: str, limit: int = 8) -> list[dict[str, Any]]:
    tokens = [t.strip().replace('"', "") for t in query.strip().split() if t.strip()]
    if not tokens:
        return []

    fts_query = " ".join(f'"{t}"*' for t in tokens)
    conn = get_db_connection()
    try:
        cursor = conn.cursor()
        rows = cursor.execute("""
            SELECT c.policy_id, c.name, c.category, c.severity, c.description, c.exclusive_group
            FROM policies_fts f
            JOIN policies_catalog c ON f.policy_id = c.policy_id
            WHERE policies_fts MATCH ?
            ORDER BY rank
            LIMIT ?
        """, (fts_query, limit)).fetchall()
        return [dict(r) for r in rows]
    finally:
        conn.close()

def get_all_policies() -> dict[str, dict[str, Any]]:
    conn = get_db_connection()
    try:
        cursor = conn.cursor()
        rows = cursor.execute("SELECT * FROM policies_catalog").fetchall()
        catalog = {}
        for r in rows:
            d = dict(r)
            d["prerequisites"] = json.loads(d["prerequisites_json"])
            catalog[d["policy_id"]] = d
        return catalog
    finally:
        conn.close()

def compile_policy_plan(enabled_ids: list[str]) -> dict[str, Any]:
    catalog = get_all_policies()
    queued_set = set(enabled_ids)

    # 1. Unroll DAG prerequisites (Diamond deduplication)
    # If a rule requires another rule, ensure the prerequisite is highlighted and satisfied
    resolved_ids: list[str] = []
    missing_prereqs: dict[str, list[str]] = {}

    for pid in enabled_ids:
        if pid not in catalog:
            continue
        resolved_ids.append(pid)
        item = catalog[pid]
        unmet = [req for req in item["prerequisites"] if req not in queued_set]
        if unmet:
            missing_prereqs[pid] = unmet

    # 2. Detect mutual exclusivity conflicts (exclusive_group)
    group_map: dict[str, list[str]] = {}
    for pid in resolved_ids:
        grp = catalog[pid].get("exclusive_group")
        if grp:
            group_map.setdefault(grp, []).append(pid)

    conflicts = []
    for grp, pids in group_map.items():
        if len(pids) > 1:
            conflicts.append({
                "group": grp,
                "policy_ids": pids,
                "policies": [catalog[p] for p in pids],
                "reason": catalog[pids[0]].get("exclusive_reason") or f"Mutually exclusive policies in group {grp}",
            })

    # 3. Categorize active rules
    categories: dict[str, list[dict[str, Any]]] = {
        "Network": [],
        "Identity": [],
        "Compute": [],
        "Storage": [],
        "Compliance": [],
    }

    for pid in resolved_ids:
        pol = dict(catalog[pid])
        pol["has_missing_prereqs"] = pid in missing_prereqs
        pol["missing_prereq_names"] = [catalog[m]["name"] for m in missing_prereqs.get(pid, []) if m in catalog]
        cat = pol["category"]
        if cat in categories:
            categories[cat].append(pol)
        else:
            categories.setdefault(cat, []).append(pol)

    # 4. Compile deployment manifest YAML
    yaml_lines = ["# Generated by thin-viewport-boilerplate policy compiler", "# Stateless Execution • Zero Database Write Locks", ""]
    for pid in resolved_ids:
        yaml_lines.append(f"# --- {catalog[pid]['name']} ({pid}) ---")
        yaml_lines.append(catalog[pid]["yaml_block"].strip())
        yaml_lines.append("")

    compiled_yaml = "\n".join(yaml_lines)

    return {
        "total_active": len(resolved_ids),
        "total_catalog": len(catalog),
        "missing_prereqs_count": len(missing_prereqs),
        "conflicts": conflicts,
        "categories": {k: v for k, v in categories.items() if v},
        "compiled_yaml": compiled_yaml,
        "active_ids": resolved_ids,
    }
