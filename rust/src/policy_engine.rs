//! policy_engine.rs — Pure-Rust DAG evaluation, prerequisite resolution, and collision detection.

use std::collections::{BTreeMap, HashMap, HashSet};
use crate::catalog::{find_policy, PolicyItem, CATALOG};

#[derive(Debug, Clone)]
#[allow(dead_code)]
pub struct ConflictView {
    pub group: String,
    pub policies: Vec<&'static PolicyItem>,
    pub reason: String,
}

#[derive(Debug, Clone)]
pub struct ActivePolicyView {
    pub item: &'static PolicyItem,
    pub has_missing_prereqs: bool,
    pub missing_prereq_names: Vec<String>,
}

#[derive(Debug, Clone)]
#[allow(dead_code)]
pub struct PolicyPlan {
    pub total_active: usize,
    pub total_catalog: usize,
    pub missing_prereqs_count: usize,
    pub conflicts: Vec<ConflictView>,
    pub categories: BTreeMap<String, Vec<ActivePolicyView>>,
    pub compiled_yaml: String,
    pub active_ids: Vec<String>,
}

pub fn compile_policy_plan(enabled_ids: &[String]) -> PolicyPlan {
    let queued_set: HashSet<&str> = enabled_ids.iter().map(|s| s.as_str()).collect();
    let mut resolved_items: Vec<&'static PolicyItem> = Vec::new();
    let mut missing_prereqs: HashMap<&str, Vec<&str>> = HashMap::new();

    for id in enabled_ids {
        if let Some(item) = find_policy(id) {
            resolved_items.push(item);
            let unmet: Vec<&str> = item
                .prerequisites
                .iter()
                .copied()
                .filter(|req| !queued_set.contains(req))
                .collect();

            if !unmet.is_empty() {
                missing_prereqs.insert(item.policy_id, unmet);
            }
        }
    }

    // 2. Detect mutual exclusivity conflicts
    let mut group_map: HashMap<&str, Vec<&'static PolicyItem>> = HashMap::new();
    for item in &resolved_items {
        if let Some(grp) = item.exclusive_group {
            group_map.entry(grp).or_default().push(item);
        }
    }

    let mut conflicts = Vec::new();
    for (grp, items) in group_map {
        if items.len() > 1 {
            let reason = items[0]
                .exclusive_reason
                .map(|s| s.to_string())
                .unwrap_or_else(|| format!("Mutually exclusive policies in group {}", grp));

            conflicts.push(ConflictView {
                group: grp.to_string(),
                policies: items,
                reason,
            });
        }
    }

    // 3. Categorize active rules
    let mut categories: BTreeMap<String, Vec<ActivePolicyView>> = BTreeMap::new();
    for item in &resolved_items {
        let has_missing = missing_prereqs.contains_key(item.policy_id);
        let missing_names: Vec<String> = missing_prereqs
            .get(item.policy_id)
            .map(|reqs| {
                reqs.iter()
                    .filter_map(|r| find_policy(r).map(|p| p.name.to_string()))
                    .collect()
            })
            .unwrap_or_default();

        let view = ActivePolicyView {
            item,
            has_missing_prereqs: has_missing,
            missing_prereq_names: missing_names,
        };

        categories
            .entry(item.category.to_string())
            .or_default()
            .push(view);
    }

    // 4. Compile deployment manifest YAML
    let mut yaml_lines = vec![
        "# Generated by thin-viewport-boilerplate policy compiler (Rust Axum Engine)".to_string(),
        "# Stateless Execution • Zero Database Write Locks • Microsecond Execution".to_string(),
        "".to_string(),
    ];

    for item in &resolved_items {
        yaml_lines.push(format!("# --- {} ({}) ---", item.name, item.policy_id));
        yaml_lines.push(item.yaml_block.trim().to_string());
        yaml_lines.push("".to_string());
    }

    let compiled_yaml = yaml_lines.join("\n");

    PolicyPlan {
        total_active: resolved_items.len(),
        total_catalog: CATALOG.len(),
        missing_prereqs_count: missing_prereqs.len(),
        conflicts,
        categories,
        compiled_yaml,
        active_ids: enabled_ids.to_vec(),
    }
}
